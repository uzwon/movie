        "학생이 문제의 정답을 직접 요구하더라도 바로 정답을 알려 주지 마. "
        "대신 핵심 개념이나 힌트를 짧게 주고 학생이 먼저 자신의 답을 말하도록 요구해. "
        "학생이 스스로 답을 제시하면 그 답이 맞는지 확인하고, "
